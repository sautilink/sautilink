import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);
const base = new URL('vendor/animateicons/', root);
const output = new URL('app/assets/huge-icons/', root);
const manifest = JSON.parse(await readFile(new URL('manifest.json', base), 'utf8'));
const provenance = [manifest.runtime, ...manifest.icons];
for (const item of provenance) {
  const bytes = await readFile(new URL(item.file, base));
  const actual = createHash('sha256').update(bytes).digest('hex');
  if (actual !== item.sha256) throw new Error(`Vendored AnimateIcons integrity mismatch: ${item.file}`);
}

const imports = manifest.icons.map((item, index) => `import { a as icon${index} } from '../${item.file}';`);
const entries = manifest.icons.map((item, index) => `  ${JSON.stringify(item.name)}: icon${index},`);
await writeFile(new URL('source/catalog.mjs', base), `${imports.join('\n')}\n\nexport default Object.freeze({\n${entries.join('\n')}\n});\n`);

const shared = {
  absWorkingDir: fileURLToPath(root),
  bundle: true,
  format: 'iife',
  minify: true,
  target: ['es2020'],
  legalComments: 'eof',
  charset: 'ascii',
  logLevel: 'warning',
};
await build({
  ...shared,
  entryPoints: [fileURLToPath(new URL('source/member-icons.mjs', base))],
  outfile: fileURLToPath(new URL('runtime.js', output)),
  globalName: 'SautiHugeIcons',
  banner: { js: '/*! AnimateIcons vanilla 0.1.0 + Hugeicons (MIT), Lucide (ISC/MIT); Motion (MIT). See /app/assets/huge-icons/NOTICE.md and LICENSE files. */' },
});
await writeFile(new URL('manifest.json', output), `${JSON.stringify(manifest, null, 2)}\n`);
const runtime = await readFile(new URL('runtime.js', output));
const families = Object.entries(manifest.icons.reduce((counts, item) => {
  const library = item.library ?? 'huge';
  counts[library] = (counts[library] ?? 0) + 1;
  return counts;
}, {})).map(([library, count]) => `${count} ${library}`).join(', ');
console.log(`Member icons: ${families}; ${runtime.length.toLocaleString('en-US')} B / ${gzipSync(runtime).length.toLocaleString('en-US')} B gzip.`);

const memberSource = new URL('src/member-animated-icons.js', root);
try {
  await readFile(memberSource);
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  console.log('Member adapter source is not present; Huge runtime built.');
  process.exit(0);
}
await build({
  ...shared,
  entryPoints: [fileURLToPath(memberSource)],
  outfile: fileURLToPath(new URL('app/assets/member-animated-icons.js', root)),
  banner: { js: '/*! SautiLink member icons. Generated by scripts/build-member-icons.mjs. */' },
});
