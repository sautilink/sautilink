import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
for (const name of ['controls', 'dialogs', 'color', 'files', 'media']) {
  await build({
    entryPoints: [fileURLToPath(new URL(`src/member-builtin-${name}.js`, root))],
    outfile: fileURLToPath(new URL(`app/assets/member-builtin-${name}.js`, root)),
    bundle: true,
    minify: true,
    format: 'iife',
    target: ['es2020'],
    charset: 'ascii',
    sourcemap: false,
    logLevel: 'warning',
    banner: { js: '/*! SautiLink member controls. Generated by scripts/build-member-controls.mjs. */' },
  });
}
console.log('Built member selects, dialogs, color editor, file and media controls.');
