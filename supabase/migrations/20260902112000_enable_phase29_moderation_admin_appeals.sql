-- Phase 29 — Moderation, Admin & Appeals
-- Staging-first moderation operations with server-owned staff roles, private reporter identity,
-- append-only decisions, member appeals, proportionate enforcement and immutable audit.

create schema if not exists private;

create table if not exists private.moderation_staff (
  user_id uuid primary key references public.social_profiles(id) on delete cascade,
  staff_role text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint moderation_staff_role_allowed
    check (staff_role = any (array['reviewer'::text, 'senior_reviewer'::text, 'auditor'::text]))
);

comment on table private.moderation_staff is
  'Server-owned Phase 29 moderation authorization. This table is outside the Data API and has no browser table grants.';

revoke all on table private.moderation_staff from public, anon, authenticated;

create or replace function private.phase29_staff_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select staff.staff_role
  from private.moderation_staff staff
  where staff.user_id = auth.uid()
    and staff.active = true
    and staff.staff_role in ('reviewer', 'senior_reviewer', 'auditor')
  limit 1
$$;

revoke all on function private.phase29_staff_role() from public, anon, authenticated;
grant usage on schema private to authenticated;
grant execute on function private.phase29_staff_role() to authenticated;

