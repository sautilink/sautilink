-- Rebuild report validator to capture immutable review context while keeping reporter identity private.
create or replace function private.validate_social_report_insert()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_uid uuid := auth.uid();
  target_owner uuid;
  snapshot jsonb;
begin
  if current_uid is null then
    raise exception 'AUTH_REQUIRED' using errcode = '42501';
  end if;

  new.reporter_id := current_uid;
  new.report_status := 'open';
  new.status_updated_at := now();
  new.reviewed_at := null;
  new.resolved_at := null;
  new.moderation_note := null;
  new.assigned_to := null;
  new.target_owner_id := null;
  new.context_snapshot := null;
  new.policy_version := 'safety-v1';
  new.priority := case
    when new.reason in ('hate', 'privacy', 'impersonation') then 'high'
    when new.reason = 'spam' then 'medium'
    else 'medium'
  end;
  new.details := nullif(btrim(coalesce(new.details, '')), '');

  if new.target_type in ('profile', 'post', 'comment')
     and new.target_id !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then
    raise exception 'REPORT_TARGET_INVALID' using errcode = '22023';
  end if;

  if new.target_type = 'message'
     and new.target_id !~ '^[0-9]{1,19}$' then
    raise exception 'REPORT_TARGET_INVALID' using errcode = '22023';
  end if;

  case new.target_type
    when 'profile' then
      select profile.id,
             jsonb_build_object(
               'type', 'profile',
               'username', profile.username,
               'display_name', profile.display_name,
               'bio', left(profile.bio, 500),
               'is_discoverable', profile.is_discoverable
             )
        into target_owner, snapshot
      from public.social_profiles profile
      where profile.id = new.target_id::uuid;
    when 'post' then
      select post.author_id,
             jsonb_build_object(
               'type', 'post',
               'author_id', post.author_id,
               'body', left(post.body, 1000),
               'visibility', post.visibility,
               'created_at', post.created_at,
               'media_count', post.media_count
             )
        into target_owner, snapshot
      from public.social_posts post
      where post.id = new.target_id::uuid;
    when 'comment' then
      select comment.author_id,
             jsonb_build_object(
               'type', 'comment',
               'author_id', comment.author_id,
               'post_id', comment.post_id,
               'body', left(comment.body, 1000),
               'created_at', comment.created_at
             )
        into target_owner, snapshot
      from public.social_post_comments comment
      where comment.id = new.target_id::uuid;
    when 'message' then
      select message.sender_id,
             jsonb_build_object(
               'type', 'message',
               'sender_id', message.sender_id,
               'conversation_id', message.conversation_id,
               'body', left(message.body, 4000),
               'sent_at', message.sent_at
             )
        into target_owner, snapshot
      from public.dm_messages message
      join public.dm_conversations conversation
        on conversation.id = message.conversation_id
      where message.id = new.target_id::bigint
        and (
          conversation.member_one_id = current_uid
          or conversation.member_two_id = current_uid
        );
    else
      raise exception 'REPORT_TARGET_NOT_LIVE' using errcode = '0A000';
  end case;

  if not found then
    raise exception 'REPORT_TARGET_UNAVAILABLE' using errcode = 'P0002';
  end if;

  if target_owner = current_uid then
    raise exception 'SELF_REPORT_NOT_ALLOWED' using errcode = '22023';
  end if;

  new.target_owner_id := target_owner;
  new.context_snapshot := snapshot;
  return new;
end;
$$;

revoke all on function private.validate_social_report_insert() from public, anon, authenticated;

create or replace function private.validate_phase29_action_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_uid uuid := auth.uid();
  staff_role_value text;
  report_target_type text;
  report_target_id text;
  report_target_owner uuid;
  appeal_action_id bigint;
  original_report_id bigint;
  original_target_type text;
  original_target_id text;
  original_target_owner uuid;
begin
  staff_role_value := private.phase29_staff_role();

  if staff_role_value is null or staff_role_value not in ('reviewer', 'senior_reviewer') then
    raise exception 'MODERATION_STAFF_REQUIRED' using errcode = '42501';
  end if;

  new.reason := btrim(coalesce(new.reason, ''));
  new.policy_version := nullif(btrim(coalesce(new.policy_version, '')), '');
  if new.policy_version is null then new.policy_version := 'safety-v1'; end if;
  new.created_at := now();

  if new.action_type in ('appeal_upheld', 'appeal_reversed') then
    if staff_role_value <> 'senior_reviewer' then
      raise exception 'SENIOR_REVIEW_REQUIRED' using errcode = '42501';
    end if;
    if new.appeal_id is null then
      raise exception 'APPEAL_REQUIRED' using errcode = '22023';
    end if;

    select appeal.action_id
      into appeal_action_id
    from public.social_moderation_appeals appeal
    where appeal.id = new.appeal_id
      and appeal.appeal_status in ('open', 'reviewing');

    if not found then
      raise exception 'APPEAL_UNAVAILABLE' using errcode = 'P0002';
    end if;

    select action.report_id, action.target_type, action.target_id, action.target_owner_id
      into original_report_id, original_target_type, original_target_id, original_target_owner
    from public.social_moderation_actions action
    where action.id = appeal_action_id;

    if not found then
      raise exception 'ACTION_UNAVAILABLE' using errcode = 'P0002';
    end if;

    new.report_id := original_report_id;
    new.target_type := original_target_type;
    new.target_id := original_target_id;
    new.target_owner_id := original_target_owner;
  else
    if new.appeal_id is not null then
      raise exception 'APPEAL_NOT_ALLOWED' using errcode = '22023';
    end if;

    select report.target_type, report.target_id, report.target_owner_id
      into report_target_type, report_target_id, report_target_owner
    from public.social_reports report
    where report.id = new.report_id
      and report.report_status in ('open', 'reviewing');

    if not found then
      raise exception 'REPORT_UNAVAILABLE' using errcode = 'P0002';
    end if;

    if new.action_type = 'content_removed' and staff_role_value <> 'senior_reviewer' then
      raise exception 'SENIOR_REVIEW_REQUIRED' using errcode = '42501';
    end if;

    if new.action_type in ('visibility_limited', 'content_removed')
       and report_target_type not in ('post', 'comment') then
      raise exception 'ACTION_NOT_SUPPORTED_FOR_TARGET' using errcode = '22023';
    end if;

    new.target_type := report_target_type;
    new.target_id := report_target_id;
    new.target_owner_id := report_target_owner;
  end if;

  return new;
end;
$$;

