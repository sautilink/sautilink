create or replace function private.validate_phase29_appeal_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_uid uuid := auth.uid();
  staff_role_value text;
begin
  staff_role_value := private.phase29_staff_role();

  if staff_role_value is null or staff_role_value not in ('reviewer', 'senior_reviewer') then
    raise exception 'MODERATION_STAFF_REQUIRED' using errcode = '42501';
  end if;

  if new.action_id <> old.action_id
     or new.appellant_id <> old.appellant_id
     or new.reason <> old.reason
     or new.created_at <> old.created_at then
    raise exception 'APPEAL_IMMUTABLE_FIELDS' using errcode = '22023';
  end if;

  if new.appeal_status = 'reviewing' then
    new.assigned_to := current_uid;
    new.decision_reason := null;
    new.decided_at := null;
  elsif new.appeal_status in ('upheld', 'reversed') then
    if staff_role_value <> 'senior_reviewer' then
      raise exception 'SENIOR_REVIEW_REQUIRED' using errcode = '42501';
    end if;
    if new.decision_reason is null or char_length(btrim(new.decision_reason)) < 1 then
      raise exception 'APPEAL_DECISION_REASON_REQUIRED' using errcode = '22023';
    end if;
    new.assigned_to := current_uid;
    new.decided_at := now();
  elsif new.appeal_status <> old.appeal_status then
    raise exception 'INVALID_APPEAL_TRANSITION' using errcode = '22023';
  end if;

  new.updated_at := now();
  return new;
end;
$$;

